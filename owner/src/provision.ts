import { productOf, type Deployment } from './registry.ts'

/**
 * What to actually run to stand a customer up.
 *
 * **This console does not provision anything itself, and that is a decision
 * rather than a gap.** Provisioning creates a database, writes secrets and
 * starts a container; a web page that does it holds credentials for every
 * customer's infrastructure and turns one stolen session into every town at
 * once. What it does instead is produce the exact environment and the exact
 * commands, from facts it already holds, so the operator's part is copying
 * rather than remembering — which is where the mistakes actually come from.
 *
 * The one secret in here is the ops token, and it is shown **once**, at the
 * moment the deployment is added. After that the registry holds only a sealed
 * copy it can present to the deployment, never display.
 */
export function envFile(d: Deployment, opsToken: string | null): string {
  const lines: string[] = []
  const push = (k: string, v: string) => lines.push(`${k}=${v}`)

  lines.push(`# ${productOf(d.tier)} — ${d.slug}`)
  lines.push(`# Generated by the owner portal. Fill in the blanks marked TODO.`)
  lines.push('')
  push('NODE_ENV', 'production')
  push('DATABASE_URL', `postgres://elgu:TODO-PASSWORD@localhost:5432/elgu_${d.slug.replace(/-/g, '_')}`)
  push('JWT_SECRET', 'TODO  # openssl rand -hex 32')
  lines.push('')
  lines.push('# Which government this instance is. Stamped on every account —')
  lines.push('# changing the code later locks out every resident at once.')
  if (d.tier === 'barangay') {
    push('DEPLOYMENT_TIER', 'barangay')
    push('BARANGAY_ID', d.barangay_id ?? '')
    push('BARANGAY_ROSTER', `/etc/elgu/${d.slug}-roster.json`)
  }
  push('MUNICIPALITY_CODE', d.municipality_code)
  push('MUNICIPALITY_NAME', quote(d.municipality_name))
  push('MUNICIPALITY_PROVINCE', quote(d.municipality_province))
  if (d.tier === 'municipal') {
    push('BARANGAY_ROSTER', `/etc/elgu/${d.slug}-roster.json`)
    push('BARANGAY_COUNT', 'TODO  # the real number of barangays; refuses a short roster')
  }
  lines.push('')
  lines.push('# The address residents reach. Every certificate QR is built from it')
  lines.push('# and the PDF is stored, so this cannot be corrected after issue.')
  push('PUBLIC_URL', d.public_url)
  lines.push('')
  push('ADMIN_EMAIL', d.contact_email || `TODO  # the ${d.tier === 'barangay' ? 'captain' : 'hall'}'s administrator address`)
  push('ADMIN_NAME', quote(d.tier === 'barangay' ? `Barangay ${d.barangay_name} — Administrator` : 'Office of the Mayor — Administrator'))
  push('SEED_PASSWORD', 'TODO  # from a secret store; the administrator changes it on first sign-in')
  lines.push('')
  lines.push('# Lets the owner portal ask this instance how it is. Without it the')
  lines.push('# ops route is not mounted at all and monitoring shows "no endpoint".')
  push('OPS_TOKEN', opsToken ?? 'TODO  # rotate one in the owner portal and paste it here')
  lines.push('')
  lines.push('# Everything below is per-deployment and is not optional for a real LGU —')
  lines.push('# see DEPLOY.md, "Before you take real submissions".')
  push('SMTP_URL', 'TODO')
  push('MAIL_FROM', `${quote(productOf(d.tier))} <no-reply@${host(d.public_url)}>`)
  push('CLAMAV_HOST', 'TODO')
  push('UPLOAD_DIR', `/var/lib/elgu/${d.slug}/uploads`)
  push('TRUST_PROXY', '1')
  if (d.tier === 'municipal') {
    lines.push('')
    lines.push('# Only where the hall takes money. A barangay settles at the counter.')
    push('PAYMENT_PROVIDER', 'TODO  # never "mock" in production')
    push('PAYMENT_SECRET', 'TODO')
  }
  return lines.join('\n') + '\n'
}

/** The roster file a barangay deployment needs: one row is enough. */
export function rosterFile(d: Deployment): string {
  if (d.tier !== 'barangay') {
    return '[\n  { "id": "poblacion", "name": "Poblacion" }\n  // … every barangay in the municipality, from the PSGC listing\n]\n'
  }
  return JSON.stringify([{ id: d.barangay_id, name: d.barangay_name }], null, 2) + '\n'
}

export function commands(d: Deployment): string {
  const db = `elgu_${d.slug.replace(/-/g, '_')}`
  return [
    `# 1. Its own database — never shared with another customer.`,
    `createdb ${db}`,
    ``,
    `# 2. Its environment and roster, from the two files above.`,
    `install -m 600 ${d.slug}.env /etc/elgu/${d.slug}.env`,
    `install -m 644 ${d.slug}-roster.json /etc/elgu/${d.slug}-roster.json`,
    ``,
    `# 3. Schema and seed. This creates the administrator and nobody else.`,
    `cd server && env $(grep -v '^#' /etc/elgu/${d.slug}.env | xargs) npm run provision`,
    ``,
    `# 4. The web app, built for the right product. The manifest and the iOS`,
    `#    home-screen label are baked in here and cannot be fixed at runtime.`,
    d.tier === 'barangay' ? `VITE_PRODUCT=barangay npm run build` : `npm run build`,
    ``,
    `# 5. Start it, and point ${host(d.public_url)} at it.`,
    `cd server && env $(grep -v '^#' /etc/elgu/${d.slug}.env | xargs) npm start`,
  ].join('\n')
}

const quote = (v: string) => (/\s/.test(v) ? `"${v}"` : v)
const host = (url: string) => {
  try { return new URL(url).host } catch { return 'localhost' }
}
